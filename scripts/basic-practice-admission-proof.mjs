export const BASIC_ORIGINAL_SCOPE_DIAGNOSTIC=Object.freeze({
 code:'practice_original_scope',
 message:'Unassisted Original practice retains every attack in the selected Human parts and groups physical targets within that scope. Unselected accompaniment stays Machine. Known unsupported original instruments assigned Human are rejected; physical playability is checked independently.',
 note_id:null,severity:'warning',
});
/** Full-scope Original keeps the immutable assignment from the assistance
 * oracle, but its policy disclosure intentionally describes selected-scope
 * practice. Every preceding source diagnostic remains exact and ordered. */
export function validateBasicOriginalAdmission(checked,assistanceOriginal,{compareAssignment=true}={}){
 const {diagnostics,...assignment}=checked,{diagnostics:originalDiagnostics,...originalAssignment}=assistanceOriginal;
 assert.ok(Array.isArray(originalDiagnostics)&&originalDiagnostics.length>0);
 assert.equal(originalDiagnostics.at(-1).code,'assistance_scope_limits');
 assert.equal(originalDiagnostics.filter(row=>row.code==='assistance_scope_limits').length,1);
 assert.deepEqual(diagnostics,[...originalDiagnostics.slice(0,-1),BASIC_ORIGINAL_SCOPE_DIAGNOSTIC],'Original admission must retain every source warning and the exact selected-scope practice disclosure');
 if(compareAssignment)assert.deepEqual(assignment,originalAssignment,'Original admission changed an immutable assignment, receipt, target or ownership field');
 return checked;
}
